package main

import (
	"context"
	"encoding/json"
	"fmt"
	"log/slog"
	"os"
	"time"

	"github.com/spf13/cobra"

	"github.com/ik-vidya/smsgateway/internal/modem"
	"github.com/ik-vidya/smsgateway/internal/probe"
	"github.com/ik-vidya/smsgateway/internal/profiles"
)

func cmdProbe() *cobra.Command {
	var (
		port         string
		baud         int
		asJSON       bool
		output       string
		name         string
		force        bool
		timeout      time.Duration
		cregTimeout  time.Duration
		scanNetworks bool
		copsTimeout  time.Duration
	)

	c := &cobra.Command{
		Use:   "probe",
		Short: "Опрос модема и генерация скелета профиля",
		Long: `Опрашивает AT-модем через последовательный порт: идентификация,
SIM, сеть, SMS, питание, поддержка опциональных AT-команд.
По результатам рекомендует обходы и определяет подходящий
профиль через profiles.Auto().

С --output PATH и --name NAME генерирует Go-файл скелета
профиля. Скелет содержит маркер "// generated by smsgateway
probe" — при повторном запуске он будет перезаписан. Файл без
маркера не перезаписывается без --force.

AT+CREG? и AT+CGREG? опрашиваются с отдельным таймаутом
--creg-timeout (по умолчанию 10s): SIM800L в роуминге 2G
может «думать» дольше остальных команд, и при общем
--timeout=5s ответ не успевает прийти.

AT+COPS=? (сканирование сетей) НЕ входит в базовый опрос: он
медленный (до 2-3 минут на SIM800). Включается флагом
--scan-networks с отдельным таймаутом --cops-timeout.`,

		SilenceUsage:  true,
		SilenceErrors: true,
		RunE: func(_ *cobra.Command, _ []string) error {
			return runProbe(port, baud, asJSON, output, name, force,
				timeout, cregTimeout, scanNetworks, copsTimeout)
		},
	}

	c.Flags().StringVar(&port, "port", "",
		"последовательный порт (обязателен)")
	c.Flags().IntVar(&baud, "baud", 115200, "скорость порта")
	c.Flags().BoolVar(&asJSON, "json", false,
		"вывести результат в JSON")
	c.Flags().StringVar(&output, "output", "",
		"путь для генерации Go-файла скелета профиля")
	c.Flags().StringVar(&name, "name", "",
		"имя профиля для --output (lowercase, [a-z][a-z0-9]*)")
	c.Flags().BoolVar(&force, "force", false,
		"перезаписать --output, даже если он не был сгенерирован probe")
	c.Flags().DurationVar(&timeout, "timeout", 5*time.Second,
		"таймаут одной AT-команды (кроме CREG/CGREG — "+
			"см. --creg-timeout)")
	c.Flags().DurationVar(&cregTimeout, "creg-timeout", 10*time.Second,
		"таймаут AT+CREG? и AT+CGREG? (SIM800L в роуминге "+
			"может «думать» дольше остальных)")
	c.Flags().BoolVar(&scanNetworks, "scan-networks", false,
		"выполнить AT+COPS=? (медленно, до 2-3 минут)")
	c.Flags().DurationVar(&copsTimeout, "cops-timeout", 180*time.Second,
		"таймаут AT+COPS=? (при --scan-networks)")
	_ = c.MarkFlagRequired("port")
	return c
}

func runProbe(port string, baud int, asJSON bool,
	output, name string, force bool,
	timeout, cregTimeout time.Duration, scanNetworks bool,
	copsTimeout time.Duration) error {

	if output != "" && name == "" {
		return fmt.Errorf("для --output обязателен --name")
	}

	sp, err := modem.OpenSerial(modem.SerialConfig{
		Port: port,
		Baud: baud,
	})
	if err != nil {
		return fmt.Errorf("открытие порта: %w", err)
	}

	logger := slogAdapter{slog.Default()}
	m, err := modem.NewModem(sp, profiles.Generic{}, timeout, logger)
	if err != nil {
		_ = sp.Close()
		return fmt.Errorf("создание Modem: %w", err)
	}
	defer func() { _ = m.Close() }()

	// Сливаем URC в /dev/null: modem.NewModem создаёт URC-канал,
	// и если модем пришлёт URC посреди probe (RING, +CREG и т.п.),
	// reader заблокируется, если никто не читает. Горутина
	// завершится, когда m.Close() закроет канал.
	go func() {
		for range m.URCs() {
		}
	}()

	ctx := context.Background()
	if _, err := m.Exec(ctx, "AT"); err != nil {
		return fmt.Errorf("модем не отвечает на AT: %w", err)
	}

	res, err := probe.Run(ctx, m, probe.Options{
		CmdTimeout:          timeout,
		CREGTimeout:         cregTimeout,
		ScanNetworks:        scanNetworks,
		ScanNetworksTimeout: copsTimeout,
	})
	if err != nil {
		return err
	}
	res.Port = port

	if output != "" {
		if err := res.WriteProfile(output, name, force); err != nil {
			return err
		}
		fmt.Printf("Скелет профиля записан: %s\n", output)
		fmt.Printf("Не забудьте зарегистрировать %q в internal/profiles/profile.go\n",
			name)
		return nil
	}

	if asJSON {
		enc := json.NewEncoder(os.Stdout)
		enc.SetIndent("", "  ")
		return enc.Encode(res)
	}

	res.RenderHuman(os.Stdout)
	return nil
}
