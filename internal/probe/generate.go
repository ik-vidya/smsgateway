// Package probe, файл generate.go — генерация скелета профиля
// по результатам опроса.
package probe

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// generatedMarker — первая строка сгенерированного файла.
//
// Используется для двух целей:
//   - отличить сгенерированный файл от написанного вручную
//     (при --force: перезаписывать только если этот маркер есть,
//     иначе отказаться и потребовать явного удаления);
//   - подсказка разработчику, что файл нужно доработать вручную.
const generatedMarker = "// generated by smsgateway probe"

// GenerateProfile генерирует Go-код скелета профиля.
//
// name — имя профиля (lowercase, [a-z][a-z0-9]*).
func (r *Result) GenerateProfile(name string) (string, error) {
	if !validProfileName(name) {
		return "", fmt.Errorf(
			"некорректное имя профиля %q "+
				"(ожидается [a-z][a-z0-9]*)", name)
	}

	goName := capitalize(name)

	var b strings.Builder

	fmt.Fprintf(&b, "%s на основе данных %s (%s).\n",
		generatedMarker, r.Port, r.Info.Model)
	b.WriteString("//\n")
	b.WriteString("// ВНИМАНИЕ: это скелет. Workarounds и хуки пусты —\n")
	b.WriteString("// заполните их вручную по результатам тестов на\n")
	b.WriteString("// реальном железе. См. внутренние TODO.\n\n")
	b.WriteString("package profiles\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"context\"\n")
	b.WriteString("\t\"strings\"\n")
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "// %s — профиль для модема %s %s.\n",
		goName, orDash(r.Info.Manufacturer), orDash(r.Info.Model))
	b.WriteString("//\n")
	b.WriteString("// Сгенерирован командой `smsgateway probe --output ...`.\n")
	b.WriteString("// Специфических обходов пока не выявлено: все хуки —\n")
	b.WriteString("// no-op, как у Generic. Проверьте на реальном железе\n")
	b.WriteString("// следующие места (по необходимости):\n")
	b.WriteString("//   - ForceUCS2ForAllSMS: если модем искажает GSM-7;\n")
	b.WriteString("//   - UseCSMPForSRR: если не приходят delivery reports;\n")
	b.WriteString("//   - AlignReadStorage: если AT+CMGL возвращает пусто;\n")
	b.WriteString("//   - PinAttemptsAT: если есть AT-команда для попыток PIN.\n")
	fmt.Fprintf(&b, "type %s struct{}\n\n", goName)

	fmt.Fprintf(&b, "func (%s) Name() string { return %q }\n\n",
		goName, name)

	// Match.
	b.WriteString("func (")
	b.WriteString(goName)
	b.WriteString(") Match(info Info) bool {\n")
	b.WriteString("\tm := strings.ToUpper(info.Manufacturer)\n")
	b.WriteString("\tmod := strings.ToUpper(info.Model)\n")
	if r.Info.Manufacturer != "" {
		fmt.Fprintf(&b,
			"\tif strings.Contains(m, %q) {\n\t\treturn true\n\t}\n",
			strings.ToUpper(r.Info.Manufacturer))
	}
	if r.Info.Model != "" {
		fmt.Fprintf(&b,
			"\tif strings.Contains(mod, %q) {\n\t\treturn true\n\t}\n",
			strings.ToUpper(r.Info.Model))
	}
	b.WriteString("\treturn false\n}\n\n")

	// Workarounds — пустые с TODO.
	b.WriteString("func (")
	b.WriteString(goName)
	b.WriteString(") Workarounds() Workarounds {\n")
	b.WriteString("\t// TODO(профиль): заполнить по результатам тестов.\n")
	b.WriteString("\treturn Workarounds{}\n}\n\n")

	// PreInitHook.
	b.WriteString("func (")
	b.WriteString(goName)
	b.WriteString(") PreInitHook(ctx context.Context, m ModemHook) error {\n")
	b.WriteString("\t// TODO(профиль): специфичные AT-команды инициализации.\n")
	b.WriteString("\treturn nil\n}\n\n")

	// PreSendHook.
	b.WriteString("func (")
	b.WriteString(goName)
	b.WriteString(") PreSendHook(ctx context.Context, m ModemHook) error {\n")
	b.WriteString("\t// TODO(профиль): специфичные AT-команды перед отправкой.\n")
	b.WriteString("\treturn nil\n}\n\n")

	b.WriteString("// ЗАБЫЛИ ЗАРЕГИСТРИРОВАТЬ? Добавьте профиль в\n")
	fmt.Fprintf(&b,
		"// internal/profiles/profile.go: Get(%q) и Auto().\n", name)

	return b.String(), nil
}

// WriteProfile пишет сгенерированный код в файл.
//
// Если файл существует:
//   - и содержит generatedMarker — перезаписываем (это наш же
//     скелет);
//   - и не содержит marker — отказываемся, если !force.
func (r *Result) WriteProfile(path, name string, force bool) error {
	code, err := r.GenerateProfile(name)
	if err != nil {
		return err
	}

	if data, err := os.ReadFile(path); err == nil {
		firstLine := strings.SplitN(string(data), "\n", 2)[0]
		ours := strings.HasPrefix(firstLine, generatedMarker)
		if !ours && !force {
			return fmt.Errorf(
				"файл %q существует и не сгенерирован probe "+
					"(нет маркера %q); используйте --force "+
					"для перезаписи", path, generatedMarker)
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("stat %q: %w", path, err)
	}

	if dir := filepath.Dir(path); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("создание каталога %q: %w", dir, err)
		}
	}
	if err := os.WriteFile(path, []byte(code), 0o644); err != nil {
		return fmt.Errorf("запись %q: %w", path, err)
	}
	return nil
}

var profileNameRe = regexp.MustCompile(`^[a-z][a-z0-9]*$`)

func validProfileName(s string) bool {
	return profileNameRe.MatchString(s)
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
